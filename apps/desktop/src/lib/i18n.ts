export const builtInLanguages = [zhCN, enUS];
export const defaultLanguage = zhCN;

export function translate(
  pack: LanguagePack,
  key: string,
  values: Record<string, string | number> = {}
): string {
  const ownText = pack.strings[key];
  let text = typeof ownText === "string" && ownText.length > 0 && ownText !== key ? ownText : enUS.strings[key] ?? key;
  for (const [name, value] of Object.entries(values)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

export function parseLanguagePack(raw: string): LanguagePack {
  const payload = JSON.parse(raw) as Partial<LanguagePack>;
  if (!payload || typeof payload !== "object") {
    throw new Error("language payload must be an object");
  }
  if (!payload.strings || typeof payload.strings !== "object") {
    throw new Error("language payload must include strings");
  }
  if (!Object.values(payload.strings).some((value) => typeof value === "string" && value.trim().length > 0)) {
    throw new Error("language payload must include at least one translated string");
  }

  const strings: TranslationMap = {};
  for (const key of Object.keys(enUS.strings).sort()) {
    const value = payload.strings[key];
    strings[key] = typeof value === "string" && value.length > 0 ? value : enUS.strings[key];
  }

  return {
    id: typeof payload.id === "string" && payload.id ? payload.id : "custom",
    name: typeof payload.name === "string" && payload.name ? payload.name : "Custom language",
    strings
  };
}

export function buildLanguageTemplate(): LanguagePack {
  const strings: TranslationMap = {};
  for (const key of Object.keys(enUS.strings).sort()) {
    strings[key] = enUS.strings[key];
  }

  return {
    id: "community-locale",
    name: "Community Locale",
    strings
  };
}
