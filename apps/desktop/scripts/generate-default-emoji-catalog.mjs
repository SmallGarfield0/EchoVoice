import { existsSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const scriptDirectory = dirname(fileURLToPath(import.meta.url));
const desktopDirectory = resolve(scriptDirectory, "..");
const catalogPath = resolve(desktopDirectory, "src", "lib", "default-emoji-catalog.ts");
const legacyCatalogPath = resolve(desktopDirectory, "src", "lib", "emoji.ts");
const sourceURL = "https://unicode.org/Public/emoji/latest/emoji-test.txt";
const expectedVersion = "17.0";
const maximumIDLength = 12;

const categoryByUnicodeGroup = new Map([
  ["Smileys & Emotion", "people"],
  ["People & Body", "people"],
  ["Animals & Nature", "nature"],
  ["Food & Drink", "food"],
  ["Activities", "activities"],
  ["Travel & Places", "travel"],
  ["Objects", "objects"],
  ["Symbols", "symbols"],
  ["Flags", "flags"]
]);

const genericIDWords = new Set([
  "and",
  "button",
  "face",
  "flag",
  "of",
  "person",
  "sign",
  "symbol",
  "the",
  "with"
]);

const catalogModulePath = existsSync(catalogPath) ? catalogPath : legacyCatalogPath;
const currentCatalog = await import(`${pathToFileURL(catalogModulePath).href}?generated=${Date.now()}`);
const currentEmojis = Array.isArray(currentCatalog.defaultEmojis) ? currentCatalog.defaultEmojis : [];
const currentByValue = new Map(currentEmojis.map((emoji) => [emoji.value, emoji]));
const reservedIDs = new Set(currentEmojis.map((emoji) => emoji.id));

const response = await fetch(sourceURL);
if (!response.ok) throw new Error(`Unable to download Unicode emoji data: ${response.status}`);
const source = await response.text();
const version = source.match(/^# Version: ([0-9.]+)$/m)?.[1] ?? "";
if (version !== expectedVersion) {
  throw new Error(`Expected Unicode Emoji ${expectedVersion}, received ${version || "an unknown version"}`);
}

let unicodeGroup = "";
let unicodeSubgroup = "";
const usedIDs = new Set();
const includedValues = new Set();
const records = [];

for (const line of source.split(/\r?\n/)) {
  if (line.startsWith("# group: ")) {
    unicodeGroup = line.slice("# group: ".length).trim();
    continue;
  }
  if (line.startsWith("# subgroup: ")) {
    unicodeSubgroup = line.slice("# subgroup: ".length).trim();
    continue;
  }
  const match = line.match(/^([0-9A-F ]+)\s+;\s+fully-qualified\s+#\s+(.+?)\s+E[0-9.]+\s+(.+)$/);
  if (!match) continue;
  const codePoints = match[1].trim().split(/\s+/).map((value) => Number.parseInt(value, 16));
  if (codePoints.some((value) => value >= 0x1f3fb && value <= 0x1f3ff)) continue;
  const category = categoryByUnicodeGroup.get(unicodeGroup);
  if (!category) continue;

  const value = match[2];
  const name = normalizeSearchText(match[3]);
  const existing = currentByValue.get(value);
  const id = existing?.id ?? createUniqueID(name, match[1], usedIDs, reservedIDs);
  if (usedIDs.has(id)) throw new Error(`Duplicate emoji ID generated: ${id}`);
  usedIDs.add(id);
  includedValues.add(value);
  records.push({
    id,
    value,
    category,
    keywords: uniqueStrings([
      ...(existing?.keywords ?? []),
      name,
      normalizeSearchText(unicodeSubgroup.replaceAll("-", " "))
    ])
  });
}

for (const emoji of currentEmojis) {
  if (includedValues.has(emoji.value)) continue;
  if (usedIDs.has(emoji.id)) throw new Error(`Legacy emoji ID conflicts with generated catalog: ${emoji.id}`);
  usedIDs.add(emoji.id);
  records.push({ ...emoji, keywords: uniqueStrings(emoji.keywords) });
}

const lines = records.map((emoji) => (
  `  ${JSON.stringify([emoji.id, emoji.value, emoji.category, emoji.keywords])}`
));
const output = `// Generated by scripts/generate-default-emoji-catalog.mjs. Do not edit manually.
// Source: Unicode Emoji ${version}, ${sourceURL}
// Copyright Unicode, Inc. Licensed under the Unicode License v3.

export const unicodeEmojiVersion = ${JSON.stringify(version)};

export type DefaultEmojiCategory =
  | "recent"
  | "people"
  | "symbols"
  | "nature"
  | "food"
  | "activities"
  | "travel"
  | "objects"
  | "flags";

export type DefaultEmoji = {
  id: string;
  value: string;
  category: Exclude<DefaultEmojiCategory, "recent">;
  keywords: string[];
};

export const defaultEmojiCategories: Array<{
  id: Exclude<DefaultEmojiCategory, "recent">;
  labelKey: string;
}> = [
  { id: "people", labelKey: "emoji.categoryPeople" },
  { id: "symbols", labelKey: "emoji.categorySymbols" },
  { id: "nature", labelKey: "emoji.categoryNature" },
  { id: "food", labelKey: "emoji.categoryFood" },
  { id: "activities", labelKey: "emoji.categoryActivities" },
  { id: "travel", labelKey: "emoji.categoryTravel" },
  { id: "objects", labelKey: "emoji.categoryObjects" },
  { id: "flags", labelKey: "emoji.categoryFlags" }
];

type DefaultEmojiSeed = readonly [
  id: string,
  value: string,
  category: Exclude<DefaultEmojiCategory, "recent">,
  keywords: readonly string[]
];

const defaultEmojiSeeds: readonly DefaultEmojiSeed[] = [
${lines.join(",\n")}
];

export const defaultEmojis: DefaultEmoji[] = defaultEmojiSeeds.map(
  ([id, value, category, keywords]) => ({ id, value, category, keywords: [...keywords] })
);
`;

writeFileSync(catalogPath, output, "utf8");

const counts = Object.fromEntries(
  [...categoryByUnicodeGroup.values()]
    .filter((category, index, values) => values.indexOf(category) === index)
    .map((category) => [category, records.filter((emoji) => emoji.category === category).length])
);
console.log(`Generated ${records.length} built-in emoji from Unicode Emoji ${version}`);
console.log(JSON.stringify(counts));

function normalizeSearchText(value) {
  return value
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, " ")
    .trim();
}

function createUniqueID(name, codePointSource, used, reserved) {
  const words = name.split(" ").filter((word) => word && !genericIDWords.has(word));
  const fallbackWords = name.split(" ").filter(Boolean);
  const slug = (words.length > 0 ? words : fallbackWords).join("_") || `u${codePointSource.split(" ")[0].toLowerCase()}`;
  const base = slug.slice(0, maximumIDLength).replace(/_+$/g, "") || "emoji";
  if (!used.has(base) && !reserved.has(base)) return base;
  for (let suffix = 2; suffix < 10_000; suffix += 1) {
    const suffixText = `_${suffix}`;
    const candidate = `${base.slice(0, maximumIDLength - suffixText.length).replace(/_+$/g, "")}${suffixText}`;
    if (!used.has(candidate) && !reserved.has(candidate)) return candidate;
  }
  throw new Error(`Unable to allocate an emoji ID for ${name}`);
}

function uniqueStrings(values) {
  return [...new Set(values.map(normalizeSearchText).filter(Boolean))];
}
